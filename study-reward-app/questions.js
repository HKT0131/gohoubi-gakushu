function randInt(min, max) { return Math.floor(Math.random() * (max - min + 1)) + min; }
function shuffle(arr) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(Math.random() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; }
  return a;
}
function pick(arr) { return arr[randInt(0, arr.length - 1)]; }

// 正解 a と誤答候補から4択を作る。候補が足りなければ fallback() で補充。
function fillChoices(a, candidates, fallback) {
  const wrong = new Set();
  for (const c of candidates) { if (wrong.size >= 3) break; if (c !== a) wrong.add(c); }
  let guard = 0;
  while (wrong.size < 3 && guard++ < 200) { const c = fallback(); if (c !== a) wrong.add(c); }
  return shuffle([a, ...wrong]);
}

// 数値の正解から、step 刻みの近い誤答を作る
function numQuestion(q, ans, step, unit = "") {
  const fmt = (v) => `${v.toLocaleString("ja-JP")}${unit}`;
  const cands = shuffle([-3, -2, -1, 1, 2, 3]).map((k) => ans + k * step).filter((v) => v > 0).map(fmt);
  return { q, a: fmt(ans), choices: fillChoices(fmt(ans), cands, () => fmt(ans + randInt(1, 9) * step)) };
}

function gcd(a, b) { return b ? gcd(b, a % b) : Math.abs(a); }
function fracStr(n, d) { const g = gcd(n, d); n /= g; d /= g; return d === 1 ? String(n) : `${n}/${d}`; }
function decStr(intVal, places) { return (intVal / 10 ** places).toFixed(places).replace(/\.?0+$/, ""); }

function makeMath() {
  const t = randInt(0, 6);
  let q, a;
  if (t === 4) {
    // 分数の足し算
    const b = randInt(2, 9), d = randInt(2, 9), x = randInt(1, b - 1), y = randInt(1, d - 1);
    const ans = fracStr(x * d + y * b, b * d);
    const n = x * d + y * b, den = b * d;
    const cands = [fracStr(x + y, b + d), fracStr(n + 1, den), fracStr(Math.max(1, n - 1), den), fracStr(n, den + 1), fracStr(x * y, b * d)];
    return { q: `${x}/${b} + ${y}/${d} = ?（約分した形）`, a: ans, choices: fillChoices(ans, shuffle(cands), () => fracStr(randInt(1, 20), randInt(2, 30))) };
  }
  if (t === 5) {
    // 小数のかけ算
    const x = randInt(11, 99), y = randInt(2, 49);
    const ans = decStr(x * y, 2);
    const cands = [decStr(x * y, 1), decStr(x * y, 3), decStr(x * y + 10, 2), decStr(Math.max(1, x * y - 10), 2)];
    return { q: `${decStr(x, 1)} × ${decStr(y, 1)} = ?`, a: ans, choices: fillChoices(ans, shuffle(cands), () => decStr(x * y + randInt(1, 30), 2)) };
  }
  if (t === 6) {
    // 一次方程式
    const c = randInt(2, 9), x = randInt(-9, 12), b = randInt(-20, 20);
    const bs = b >= 0 ? `+ ${b}` : `− ${-b}`;
    q = `${c}x ${bs} = ${c * x + b} のとき x = ?`;
    const ans = String(x);
    const cands = [String(-x), String(x + 1), String(x - 1), String(x + 2)];
    return { q, a: ans, choices: fillChoices(ans, shuffle(cands), () => String(x + randInt(-10, 10))) };
  }
  if (t === 0) { const x = randInt(12, 99), y = randInt(3, 9); q = `${x} × ${y} = ?`; a = x * y; }
  else if (t === 1) { const x = randInt(100, 999), y = randInt(100, 999); q = `${x} + ${y} = ?`; a = x + y; }
  else if (t === 2) { const p = [10, 15, 20, 25, 30, 40][randInt(0, 5)], v = randInt(2, 30) * 100; q = `${v}円の${p}%は？`; a = (v * p) / 100; }
  else { const y = randInt(3, 12), a0 = randInt(3, 30); q = `${a0 * y} ÷ ${y} = ?`; a = a0; }
  const wrong = new Set();
  while (wrong.size < 3) { const w = a + randInt(-12, 12); if (w !== a && w >= 0) wrong.add(w); }
  return { q, a: String(a), choices: shuffle([a, ...wrong].map(String)) };
}

// SPI 非言語（ランダム生成）
function makeSpi() {
  const t = randInt(0, 7);
  if (t === 0) { // 損益算：定価
    const cost = randInt(4, 30) * 100, p = pick([10, 20, 25, 30, 40, 50]);
    return numQuestion(`原価${cost.toLocaleString("ja-JP")}円の商品に${p}%の利益を見込んで定価をつけた。定価はいくら？`, cost * (100 + p) / 100, cost / 10, "円");
  }
  if (t === 1) { // 損益算：値引き後の利益
    const cost = randInt(4, 20) * 100, p = pick([20, 30, 40, 50]), d = pick([10, 20]);
    const price = cost * (100 + p) / 100, sell = price * (100 - d) / 100;
    if (sell <= cost) return makeSpi();
    return numQuestion(`原価${cost.toLocaleString("ja-JP")}円の商品に原価の${p}%の利益を見込んで定価をつけたが、定価の${d}%引きで売った。利益はいくら？`, sell - cost, cost / 20, "円");
  }
  if (t === 2) { // 速さ：時間
    const v = pick([4, 6, 12, 30, 40, 60]), mins = pick([20, 30, 40, 45, 50, 90, 100]);
    const dist = (v * mins) / 60;
    if (!Number.isInteger(dist)) return makeSpi();
    return numQuestion(`時速${v}kmで${dist}kmの道のりを進むと、何分かかる？`, mins, 10, "分");
  }
  if (t === 3) { // 速さ：平均の速さ（往復）
    const [v1, v2, avg] = pick([[4, 6, 4.8], [3, 6, 4], [6, 12, 8], [40, 60, 48], [30, 60, 40], [20, 30, 24], [60, 90, 72]]);
    const d = v1 * v2;
    return numQuestion(`${d}km離れた地点まで行きは時速${v1}km、帰りは時速${v2}kmで往復した。往復の平均の速さは時速何km？`, avg, Math.max(1, Math.round(avg / 8)), "km");
  }
  if (t === 4) { // 割合
    const total = randInt(4, 30) * 20, p = pick([15, 20, 25, 30, 35, 40, 45, 60, 75]);
    const ans = (total * p) / 100;
    if (!Number.isInteger(ans)) return makeSpi();
    return numQuestion(`ある会社の社員${total}人のうち${p}%が女性である。女性は何人？`, ans, Math.max(1, Math.round(total / 20)), "人");
  }
  if (t === 5) { // 仕事算
    const [x, y] = pick([[3, 6], [4, 12], [6, 12], [10, 15], [12, 24], [20, 30], [10, 40], [12, 6], [15, 10], [8, 24]]);
    return numQuestion(`ある仕事をAは${x}日、Bは${y}日で終える。2人で一緒に行うと何日で終わる？`, (x * y) / (x + y), 1, "日");
  }
  if (t === 6) { // 濃度
    const total = pick([100, 200, 250, 400, 500]), p = pick([4, 5, 8, 10, 12, 15, 20]);
    const salt = (total * p) / 100;
    return numQuestion(`水${total - salt}gに食塩${salt}gを溶かした食塩水の濃度は何%？`, p, pick([1, 2]), "%");
  }
  // 推論：順位
  const names = shuffle(["A", "B", "C", "D"]); // names[0] が最も高い
  const facts = shuffle([0, 1, 2].map((i) => `${names[i]}は${names[i + 1]}より背が高い`));
  const rank = randInt(1, 4);
  const label = rank === 1 ? "最も背が高い" : rank === 4 ? "最も背が低い" : `背が高い方から${rank}番目`;
  return { q: `4人について次のことがわかっている。「${facts.join("」「")}」。${label}のは誰？`, a: names[rank - 1], choices: ["A", "B", "C", "D"] };
}

// 自作問題: 1行ごとに「問題,正解,誤答1,誤答2,誤答3」（誤答は省略可）
function parseCustom(text) {
  return text.split("\n").map((l) => l.split(/[,，\t]/).map((s) => s.trim())).filter((p) => p[0] && p[1])
    .map(([q, a, ...w]) => ({ q, a, wrong: w.filter(Boolean) }));
}

const FIXED_BANKS = { general: GENERAL, it: IT, boki: BOKI };

function buildQuestions(subject, n, customText) {
  if (subject === "math") return Array.from({ length: n }, makeMath);
  if (subject === "spi") return Array.from({ length: n }, makeSpi);
  if (FIXED_BANKS[subject])
    return shuffle(FIXED_BANKS[subject]).slice(0, n).map((x) => ({ ...x, choices: shuffle(x.choices) }));

  let pool;
  if (subject === "custom") pool = parseCustom(customText || "");
  else pool = ENGLISH_WORDS.map(([w, m]) => ({ q: `「${w}」の意味は？`, a: m }));
  if (pool.length < 4) return null;

  return shuffle(pool).slice(0, n).map((item) => {
    const others = shuffle(pool.filter((p) => p.a !== item.a).map((p) => p.a));
    const wrong = [...(item.wrong || []), ...others].filter((w, i, arr) => w !== item.a && arr.indexOf(w) === i).slice(0, 3);
    return { q: item.q, a: item.a, choices: shuffle([item.a, ...wrong]) };
  });
}
